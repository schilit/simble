/// The 1024 source samples every vector was captured from, in the channel
/// layout the configuration needs.
fn source_for(params: &SbcParameters) -> Vec<i16> {
    let mono = transient_signal(1024, params.sampling_frequency);
    if params.channels() == 1 {
        mono
    } else {
        stereo_from(&mono)
    }
}

fn decode_all(frames: &[u8]) -> Vec<i16> {
    let mut decoder = SbcDecoder::new();
    let (pcm, consumed) = decoder.decode_all(frames);
    assert_eq!(
        consumed,
        frames.len(),
        "simble's decoder gave up {} bytes early",
        frames.len() - consumed
    );
    pcm
}

fn encode_all(params: SbcParameters, pcm: &[i16]) -> Vec<u8> {
    let mut encoder = SbcEncoder::new(params).unwrap();
    let mut out = Vec::new();
    for chunk in pcm.chunks_exact(encoder.pcm_len()) {
        out.extend_from_slice(&encoder.encode(chunk).unwrap());
    }
    out
}

/// libsbc encoded it, simble decodes it — the direction that matters when a
/// phone is the A2DP source and a simulated headset is the sink.
///
/// Every frame also has to pass simble's header CRC check, which `decode_all`
/// enforces by requiring the whole buffer to be consumed. That is an
/// independent test of the CRC: simble's polynomial, seed and bit coverage
/// have to match bluez's or the first frame is rejected outright.
fn assert_decodes_like_libsbc(v: &Vectors, name: &str, floor_db: f64) {
    let pcm = decode_all(v.frames);
    assert_eq!(
        pcm.len(),
        v.frames.len() / v.params.frame_length() * v.params.pcm_len(),
        "{name}: decoded the wrong number of samples"
    );
    let (snr, worst) = snr_db(v.pcm, &pcm[v.window.clone()]);
    assert!(
        snr > floor_db,
        "{name}: only {snr:.1} dB against libsbc's own decode"
    );
    assert!(worst <= 12, "{name}: one sample was off by {worst}");
}

