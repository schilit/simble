/// simble encodes it, libsbc would decode it — checked the strictest way
/// available offline: simble's bitstream against libsbc's, byte for byte.
///
/// This is a much sharper instrument than comparing decoded audio. A scale
/// factor one step out, a joint-stereo decision inverted, a bit-allocation
/// arm subtly wrong — each moves bytes here while barely moving an SNR.
///
/// It is not asserted as *exact* equality. Simble is `f64` where libsbc is
/// fixed point, so a sample sitting on a quantizer boundary can round the
/// other way, and `f64::cos`/`sin` are not bit-identical across platforms.
/// The measured agreement was 951/952, 576/576 and 480/480 bytes; requiring
/// 99% leaves room for a handful of boundary flips and none at all for a
/// semantic change.
fn assert_bitstream_matches_libsbc(v: &Vectors, name: &str) {
    let frames = encode_all(v.params, &source_for(&v.params));
    assert_eq!(
        frames.len(),
        v.frames.len(),
        "{name}: simble and libsbc disagree on frame length"
    );
    let identical = frames.iter().zip(v.frames).filter(|(a, b)| a == b).count();
    let ratio = identical as f64 / frames.len() as f64;
    assert!(
        ratio >= 0.99,
        "{name}: only {identical}/{} bytes of simble's bitstream match \
         libsbc's",
        frames.len()
    );
}

