//! SBC interop against bluez's `libsbc`, in both directions.
//!
//! Simble's own SBC tests encode with simble and decode with simble, which
//! proves only that the two halves agree — the failure mode this project has
//! been bitten by over and over. These tests use a foreign implementation as
//! the oracle instead:
//!
//! * **libsbc encodes, simble decodes.** `LIBSBC_*_FRAMES` are bitstreams
//!   libsbc produced; `LIBSBC_*_PCM` is libsbc's own decode of them. Simble's
//!   decoder has to land on the same PCM, and its header CRC has to accept
//!   every frame.
//! * **simble encodes, libsbc decodes.** Simble re-encodes the same source
//!   and its bitstream is compared against libsbc's byte for byte.
//!
//! The vectors were captured by building libsbc (LGPL-2.1) as a throwaway
//! command-line tool outside this repository and running it over the signal
//! `transient_signal` generates. **No libsbc code is vendored here** — only
//! the bytes it produced from simble's own input, which is why this file is
//! compatible with simble's Apache-2.0 licence. `docs/sbc-evaluation.md`
//! records the procedure and the full measurement table.
//!
//! The three configurations were not chosen by taste. They are the smallest
//! set that catches every deliberate break tried during mutation testing:
//! joint stereo at 44.1 kHz for the everyday case, 4 subbands at a low
//! bitpool because it is the only one that reaches the bit allocator's final
//! top-up loop, and 16 kHz because it indexes a different row of the
//! frequency-dependent loudness table.
//!
//! The test signal is transient-rich on purpose. A steady tone hides codec
//! bugs: the LC3 bug that motivated this testing method passed every
//! sine-wave assertion and still measured 11.7 dB against its reference on
//! music.

