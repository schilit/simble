// windows, and how far simble's own encoder was from libsbc's bitstream
// JOINT_STEREO: window 1024..1536, 951/952 bytes identical
// MONO: window 512..768, 576/576 bytes identical
// NARROWBAND: window 512..768, 480/480 bytes identical

/// The signal every golden vector was captured from. A byte-for-byte copy of
/// the generator in `src/audio/sbc.rs`'s unit tests, deliberately duplicated
/// so this file needs nothing from the crate's private test scaffolding — and
/// self-policing, because if the two ever drift the numbers below collapse.
fn transient_signal(samples: usize, rate: u32) -> Vec<i16> {
    let mut seed = 0x2545_F491u32;
    let mut rand = move || {
        seed = seed.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
        (seed >> 8) as f64 / f64::from(1u32 << 24) * 2.0 - 1.0
    };
    let mut chirp_phase = 0.0f64;
    (0..samples)
        .map(|i| {
            // A chirp that sweeps the whole band every 512 samples, so every
            // subband carries content within a couple of frames rather than
            // only after a second of audio.
            let sweep = (i % 512) as f64 / 512.0;
            let freq = 300.0 + sweep * (0.45 * f64::from(rate) - 300.0);
            chirp_phase += std::f64::consts::TAU * freq / f64::from(rate);
            let mut v = 0.35 * chirp_phase.sin();
            // A percussive onset every 256 samples: instant attack, fast
            // decay, broadband. This is what a codec bug shows up on.
            let env = (-((i % 256) as f64) / 40.0).exp();
            let t = i as f64 / f64::from(rate);
            v += env * (rand() * 0.5 + 0.3 * (std::f64::consts::TAU * 180.0 * t).sin());
            // A sustained chord underneath, so the low subbands are never
            // idle.
            for f in [220.0, 277.18, 329.63] {
                v += 0.07 * (std::f64::consts::TAU * f * t).sin();
            }
            // A silent gap in every 1024 samples: bit allocation has to cope
            // with a subband that carries nothing.
            if (700..760).contains(&(i % 1024)) {
                v = 0.0;
            }
            (v.clamp(-1.0, 0.999) * 30000.0) as i16
        })
        .collect()
}

/// Interleaves a second channel that shares structure with the first without
/// being a copy, so the joint-stereo decision has something to decide.
fn stereo_from(mono: &[i16]) -> Vec<i16> {
    let n = mono.len();
    mono.iter()
        .enumerate()
        .flat_map(|(i, &l)| {
            let r = ((i32::from(l) + i32::from(mono[(i + 137) % n])) / 2) as i16;
            [l, r]
        })
        .collect()
}

/// Signal-to-noise ratio of `test` against `reference` in dB, and the largest
/// single-sample error.
fn snr_db(reference: &[i16], test: &[i16]) -> (f64, i32) {
    assert_eq!(reference.len(), test.len());
    let mut signal = 0.0f64;
    let mut noise = 0.0f64;
    let mut worst = 0i32;
    for (&r, &t) in reference.iter().zip(test) {
        signal += f64::from(r) * f64::from(r);
        noise += (f64::from(r) - f64::from(t)).powi(2);
        worst = worst.max((i32::from(r) - i32::from(t)).abs());
    }
    if noise == 0.0 {
        return (f64::INFINITY, 0);
    }
    (10.0 * (signal / noise).log10(), worst)
}

