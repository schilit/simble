/// simble's encoder must reproduce the source as faithfully as libsbc's,
/// judged the same way: how close the decoded audio is to what went in.
///
/// This is the assertion that fails if the codec silently degrades while
/// every self-consistent round-trip test still passes.
#[test]
fn test_simbles_encoder_reproduces_the_source_as_faithfully_as_libsbcs() {
    for (v, name) in [
        (joint_stereo(), "joint stereo"),
        (mono(), "mono 4-subband"),
        (narrowband(), "16 kHz"),
    ] {
        let source = source_for(&v.params);
        let theirs = decode_all(v.frames);
        let mine = decode_all(&encode_all(v.params, &source));

        // Both streams carry the filterbank's round-trip delay, so both are
        // shifted by the same amount before comparing against the source.
        let delay = v.params.filter_delay() * v.params.channels();
        let window = v.window.clone();
        let shifted = window.start + delay..window.end + delay;
        let (theirs_db, _) = snr_db(&source[window.clone()], &theirs[shifted.clone()]);
        let (mine_db, _) = snr_db(&source[window], &mine[shifted]);

        // Measured, simble against libsbc: 16.88 / 16.88 dB joint stereo,
        // 16.92 / 16.92 dB mono 4-subband, 15.10 / 15.10 dB at 16 kHz — the
        // same to two decimal places in every configuration. Requiring simble
        // to stay within 1 dB catches degradation without failing on
        // rounding.
        assert!(
            mine_db > theirs_db - 1.0,
            "{name}: simble reproduces the source at {mine_db:.1} dB where \
             libsbc manages {theirs_db:.1} dB"
        );
    }
}

/// The frames carry the parameters they were encoded with, read back through
/// the A2DP frame parser rather than the codec — so a header field the codec
/// and the parser disagree about cannot hide.
#[test]
fn test_the_libsbc_frames_advertise_the_configuration_they_were_made_with() {
    use simble::classic::a2dp::SbcFrame;

    for (v, name) in [
        (joint_stereo(), "joint stereo"),
        (mono(), "mono 4-subband"),
        (narrowband(), "16 kHz"),
    ] {
        let (frame, rest) = SbcFrame::parse(v.frames).unwrap_or_else(|| panic!("{name} parses"));
        assert_eq!(SbcParameters::from_frame(&frame), v.params, "{name}");
        assert_eq!(frame.payload.len(), v.params.frame_length(), "{name}");
        assert_eq!(
            rest.len(),
            v.frames.len() - v.params.frame_length(),
            "{name}"
        );
    }
}
