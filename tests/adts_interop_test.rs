//! ADTS framing against Bumble, a foreign implementation.
//!
//! Simble's ADTS support is **framing only**: it reads and writes the header
//! that wraps AAC raw data blocks, and treats the blocks themselves as
//! opaque. Nothing here decodes AAC, and simble has no AAC codec — see
//! `docs/sbc-evaluation.md` for what implementing one would cost and why it
//! is out of scope.
//!
//! The vectors in [`BUMBLE_ADTS_FRAMES`] were produced by Bumble
//! (<https://github.com/google/bumble>, Apache-2.0):
//! `AacAudioRtpPacket.for_simple_aac(...).to_adts()` wrote them, and Bumble's
//! own `AacParser` read them back. Simble has to agree with both — the parse
//! and the write.
//!
//! Simble's parser started as a port of Bumble's, so it inherited Bumble's
//! blind spots; the tests below that are *not* Bumble vectors exist because
//! of them. Bumble ignores `protection_absent`, which puts the two CRC bytes
//! at the front of what a decoder is told is AAC payload; it ignores
//! `number_of_raw_data_blocks_in_frame`, so a four-block frame is reported as
//! playing for a quarter of its real duration; and it maps reserved
//! sampling-frequency indices to 0 Hz instead of rejecting them. Those cases
//! are hand-built, and are therefore checked against the specification
//! (ISO/IEC 13818-7 section 6.2) rather than against another implementation.

