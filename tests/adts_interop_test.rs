/// Every frame Bumble built must parse to the fields Bumble's own parser
/// read out of it.
#[test]
fn test_simble_reads_bumble_built_adts_headers_the_same_way() {
    for (bytes, frequency, channels, profile_bits, payload_len) in BUMBLE_ADTS_FRAMES {
        let (frame, rest) =
            AacFrame::parse(bytes).unwrap_or_else(|| panic!("failed to parse {frequency} Hz"));
        assert_eq!(frame.sampling_frequency, frequency);
        assert_eq!(frame.channel_configuration, channels);
        assert_eq!(frame.profile.to_bits(), profile_bits);
        assert_eq!(frame.payload.len(), payload_len);
        assert!(rest.is_empty(), "the frame is exactly aac_frame_length bytes");

        // Bumble writes MPEG-4, no CRC, one raw data block.
        assert_eq!(frame.mpeg_version, AdtsMpegVersion::Mpeg4);
        assert_eq!(frame.crc, None);
        assert_eq!(frame.raw_data_block_count, 1);
        assert_eq!(frame.sample_count(), 1024, "as Bumble's sample_count says");
    }
}

/// Re-encoding a frame Bumble wrote reproduces Bumble's bytes.
///
/// This is the check that makes an A2DP *source* trustworthy: simble's header
/// writer has to agree with a foreign one field for field, including the
/// fields simble does not otherwise care about.
#[test]
fn test_simbles_adts_writer_reproduces_bumbles_header_bytes() {
    for (bytes, frequency, ..) in BUMBLE_ADTS_FRAMES {
        let (frame, _) = AacFrame::parse(bytes).unwrap();
        let rebuilt = frame.to_bytes().expect("a parsed frame is always writable");
        assert_eq!(
            rebuilt, bytes,
            "re-encoding the {frequency} Hz frame changed it"
        );
    }
}

/// A stream that has lost sync — a dropped RTP packet, a truncated read — has
/// to be re-acquired, and the sync word alone is not enough to do it with:
/// 0xFFF turns up inside compressed audio all the time.
#[test]
fn test_a_stream_can_be_resynchronised_past_garbage() {
    let (bytes, ..) = BUMBLE_ADTS_FRAMES[0];
    let mut stream = vec![
        // A decoy sync word whose header is not valid: layer 2, and a
        // reserved sampling-frequency index.
        0xFF, 0xF4, 0x38, 0x00, 0x01, 0xA0, 0x00, 0x11, 0x22,
    ];
    let offset = stream.len();
    stream.extend_from_slice(bytes);

    assert_eq!(AacFrame::find_sync(&stream), Some(offset));
    let (frame, _) = AacFrame::parse(&stream[offset..]).unwrap();
    assert_eq!(frame.sampling_frequency, 44100);
}

