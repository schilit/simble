#[test]
fn test_a_protected_frame_keeps_its_crc_out_of_the_payload() {
    let payload = [0xAAu8, 0xBB, 0xCC, 0xDD];
    let frame_length = 7 + 2 + payload.len();
    let mut bytes = vec![
        0xFF,
        // protection_absent = 0: a CRC follows the seven-byte header.
        0xF0,
        // LC profile, 44.1 kHz (index 4), channel configuration 2.
        (1 << 6) | (4 << 2),
        (2 << 6) | ((frame_length >> 11) as u8 & 0b11),
        (frame_length >> 3) as u8,
        (((frame_length & 0b111) as u8) << 5) | 0x1F,
        0xFC,
        0x12,
        0x34,
    ];
    bytes.extend_from_slice(&payload);

    let (frame, rest) = AacFrame::parse(&bytes).expect("parses");
    assert!(rest.is_empty());
    assert_eq!(frame.crc, Some(0x1234));
    assert_eq!(
        frame.payload, payload,
        "the CRC must not be reported as AAC payload"
    );
    assert_eq!(frame.to_bytes().unwrap(), bytes, "and it round trips");
}

/// `number_of_raw_data_blocks_in_frame` is not always zero, and a frame that
/// carries four blocks plays for four times as long.
#[test]
fn test_multiple_raw_data_blocks_change_the_frame_duration() {
    let (bytes, ..) = BUMBLE_ADTS_FRAMES[0];
    let mut four = bytes.to_vec();
    four[6] |= 0b11;

    let (frame, _) = AacFrame::parse(&four).unwrap();
    assert_eq!(frame.raw_data_block_count, 4);
    assert_eq!(frame.sample_count(), 4096);
    // 4096 samples at 44.1 kHz.
    assert_eq!(frame.duration_us(), 92879);

    let (one, _) = AacFrame::parse(bytes).unwrap();
    assert_eq!(one.duration_us(), 23219);
}

/// Reserved sampling-frequency indices must be refused, not reported as
/// 0 Hz — which would make every duration downstream divide by zero.
#[test]
fn test_reserved_sampling_frequency_indices_are_refused() {
    let (bytes, ..) = BUMBLE_ADTS_FRAMES[0];
    for index in 13u8..16 {
        let mut broken = bytes.to_vec();
        broken[2] = (broken[2] & !0b0011_1100) | (index << 2);
        assert!(
            AacFrame::parse(&broken).is_none(),
            "accepted reserved sampling-frequency index {index}"
        );
    }
}

/// A frame whose `channel_configuration` is zero carries its channel layout
/// in a `program_config_element` inside the payload, so a sink cannot learn
/// the channel count from the header alone.
#[test]
fn test_a_zero_channel_configuration_is_flagged_rather_than_reported_as_zero_channels() {
    let (bytes, ..) = BUMBLE_ADTS_FRAMES[0];
    let mut pce = bytes.to_vec();
    pce[2] &= !0b1;
    pce[3] &= !0b1100_0000;

    let (frame, _) = AacFrame::parse(&pce).unwrap();
    assert_eq!(frame.channel_configuration, 0);
    assert!(frame.has_program_config_element());

    let (normal, _) = AacFrame::parse(bytes).unwrap();
    assert!(!normal.has_program_config_element());
}

/// A frame whose declared length does not cover its own header, or runs past
/// the end of the buffer, is not a frame.
#[test]
fn test_impossible_frame_lengths_are_refused() {
    let (bytes, ..) = BUMBLE_ADTS_FRAMES[0];

    // aac_frame_length = 3, shorter than the seven-byte header.
    let mut short = bytes.to_vec();
    short[3] &= !0b11;
    short[4] = 0;
    short[5] = (3 << 5) | 0x1F;
    assert!(AacFrame::parse(&short).is_none());

    // A frame that claims more bytes than are present.
    assert!(AacFrame::parse(&bytes[..bytes.len() - 1]).is_none());
    assert!(AacFrame::parse(&bytes[..3]).is_none());
}
